package types

// DeleteLibraryInput permanently deletes a library and its managed originals using the library configuration version.
type DeleteLibraryInput struct {
	RequestID       string `json:"requestId"`       // Global idempotent request identifier.
	LibraryID       string `json:"libraryId"`       // Knowledge library to permanently delete.
	ExpectedVersion int64  `json:"expectedVersion"` // Library configuration version confirmed by the user.
}

// RecoverLibraryDeletionInput resumes original-file cleanup using the persistent manifest.
type RecoverLibraryDeletionInput struct {
	RequestID       string `json:"requestId"`       // Global idempotent request identifier.
	LibraryID       string `json:"libraryId"`       // Deleted knowledge library identifier.
	ExpectedVersion int64  `json:"expectedVersion"` // Current cleanup manifest version.
}

// LibraryDeletionRecord retains minimal deletion facts and a recoverable manifest without knowledge content.
type LibraryDeletionRecord struct {
	LibraryID     string             `json:"libraryId" gorm:"primaryKey"` // Permanently revoked library identifier.
	Version       int64              `json:"version"`                     // Optimistic lock for cleanup state.
	PolicyVersion int64              `json:"policyVersion"`               // Authorization generation at deletion, used to validate recovery requests at the boundary.
	State         string             `json:"state"`                       // Locally pending or completed; the public protocol reserves blocked for remote use.
	Objects       []PurgeBlobCleanup `json:"-" gorm:"serializer:json"`    // Exact manifest of managed objects generated by the core.
}

func (LibraryDeletionRecord) TableName() string { return "knowledge_library_deletions" }

// LibraryDeletionStatus exposes cleanup counts and limits without object keys.
type LibraryDeletionStatus struct {
	LibraryID               string `json:"libraryId"`               // Deleted library identifier.
	Version                 int64  `json:"version"`                 // Cleanup state version.
	PolicyVersion           int64  `json:"policyVersion"`           // Policy generation at deletion.
	State                   string `json:"state"`                   // Locally pending or completed; the public protocol reserves blocked for remote use.
	DeletedBlobCount        int    `json:"deletedBlobCount"`        // Number of objects removed or confirmed absent.
	RetainedSharedBlobCount int    `json:"retainedSharedBlobCount"` // Number of retained objects still referenced by other sources.
	BlockedBlobCount        int    `json:"blockedBlobCount"`        // Always 0 locally; remote implementations return actual blocking diagnostics.
	PendingBlobCount        int    `json:"pendingBlobCount"`        // Number of objects not yet processed.
}
