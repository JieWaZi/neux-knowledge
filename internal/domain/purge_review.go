package types

import (
	"encoding/hex"
	"encoding/json"
	"sort"
	"strings"
)

// SourcePurgeReview is a safe projection of page purge markers without arbitrary metadata or original text.
type SourcePurgeReview struct {
	NeedsReview           bool     `json:"needsReview"`           // Retained current knowledge still requires manual review.
	UnavailableSourceIDs  []string `json:"unavailableSourceIds"`  // Stable source identifiers that are now unavailable.
	UnavailableVersionIDs []string `json:"unavailableVersionIds"` // Source version identifiers that are now unavailable.
	PurgeIDs              []string `json:"purgeIds"`              // Corresponding persistent cleanup manifest identifiers.
}

func purgeReviewIDs(ids []string) []string {
	result := []string{}
	seen := map[string]bool{}
	for _, id := range ids {
		// These identifiers are generated by the core; arbitrary text must not be exported as cleanup metadata.
		decoded, err := hex.DecodeString(id)
		if err != nil || len(decoded) != 16 || strings.ToLower(id) != id || seen[id] {
			continue
		}
		seen[id] = true
		result = append(result, id)
	}
	sort.Strings(result)
	return result
}

// ParseSourcePurgeReview projects only known fields of persistent sourcePurge without creating a second source of cleanup facts.
func ParseSourcePurgeReview(metadata JSON) *SourcePurgeReview {
	var envelope struct {
		SourcePurge *SourcePurgeReview `json:"sourcePurge"` // The only recognized persistent purge marker.
	}
	if json.Unmarshal(metadata, &envelope) != nil || envelope.SourcePurge == nil || !envelope.SourcePurge.NeedsReview {
		return nil
	}
	marker := envelope.SourcePurge
	marker.UnavailableSourceIDs = purgeReviewIDs(marker.UnavailableSourceIDs)
	marker.UnavailableVersionIDs = purgeReviewIDs(marker.UnavailableVersionIDs)
	marker.PurgeIDs = purgeReviewIDs(marker.PurgeIDs)
	return marker
}
